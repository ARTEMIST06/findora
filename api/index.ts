// Vercel serverless entry for the Express app.
//
// Why this file loads '../dist/server.cjs' and NOT '../server':
// On Vercel, this function runs from /var/task/api/index.js. The TypeScript
// source '../server' does not exist there — the repo's build script
// (`npm run build`) bundles server.ts with esbuild into dist/server.cjs.
// Importing '../server' therefore failed at runtime with
// "Cannot find module '/var/task/server'" (seen live on 2026-11-14: the
// handler below surfaced it as a JSON 500 instead of Vercel's opaque
// FUNCTION_INVOCATION_FAILED page). The dist bundle is the single source of
// truth for the server code, so this entry imports it directly.
// The import is lazy + cached, so a load failure still returns JSON 500
// with the real error instead of a dead function.
import type { IncomingMessage, ServerResponse } from 'http';

let cachedApp: any = null;

export default async function handler(req: IncomingMessage, res: ServerResponse) {
  try {
    if (!cachedApp) {
      // @ts-ignore dist/server.cjs is generated by `npm run build` (esbuild) during the Vercel build; it does not exist in a fresh checkout.
      const mod: any = await import('../dist/server.cjs');
      // dist/server.cjs is a CommonJS bundle: `await import()` exposes its
      // exports as mod.app (named) and mod.default (the whole exports
      // object, whose .default is the app). Accept any of those shapes.
      cachedApp = mod.app ?? mod.default?.default ?? mod.default ?? null;
      if (typeof cachedApp !== 'function') {
        throw new Error('Server bundle did not export an Express app');
      }
    }
    return cachedApp(req, res);
  } catch (err: any) {
    // eslint-disable-next-line no-console
    console.error('[api/index] failed to load server:', err);
    if (!res.headersSent) {
      res.statusCode = 500;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({ ok: false, error: 'API failed to start', detail: String(err?.message || err) }));
    }
  }
}
